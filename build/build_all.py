"""Builds every derived file of Whisker Quest in this repo from build/gen/ (the generated art) and code. Offline.

    python build/build_all.py [--no-cut] [--preview <dir>]   (--no-cut: reuse build/spr*, backgrounds/)

3. cut_art.py    build/spr, build/spr_scene, backgrounds/: the generated art (build/gen, ART.md), pixel-snapped
4. anim.py        mods/wq-party/fonts/WhiskerDot<v>-<cat>.ttf, faces/<cat>.png   every cat's animations
5. stage_art.py   mods/wq-party/fonts/WhiskerDot<v>-{monsters,fx,props,special}.ttf, scenes/<scene>.png,
                  mods/wq-pane/stage.js
6. palettes.py    mods/wq-chrome/scenes.js              each scene's UI colors
7. backdrop.py    mods/wq-party/backdrops/               the little stage behind each card's sprite
8. tiles.py       mods/wq-spaces/art/<place>.png         the place tiles for spaces
9. layers.js      mods/wq-{party,pane,tabs}/layers.js    each font's color layers (layerfont.py)
"""
import glob
import json
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PY = sys.executable


def run(*args):
    print('$', ' '.join(os.path.relpath(a, ROOT) if a.startswith(ROOT) else a for a in args), flush=True)
    subprocess.run([PY, *args], check=True, cwd=HERE)


def layers_js():
    party = f'{ROOT}/mods/wq-party'
    fams = {}
    for p in sorted(glob.glob(f'{party}/fonts/*.layers.json')):
        info = json.load(open(p))
        # used masks: code point -> bit mask of the color layers that glyph draws; written compactly as base 36
        used = {format(int(cp), 'x'): format(m, 'z' if False else 'x') for cp, m in info['used'].items() if m}
        # advances: art pixels per glyph, as runs [first code point, count, width] (most glyphs share one width)
        runs = []
        for cp, w in sorted((int(k), v) for k, v in info['adv'].items()):
            if runs and runs[-1][0] + runs[-1][1] == cp and runs[-1][2] == w:
                runs[-1][1] += 1
            else:
                runs.append([cp, 1, w])
        fams[info['family']] = {'base': info['base'], 'layerBase': info['layerBase'], 'stride': info['stride'],
                                'spacer': info['spacer'], 'colors': info['colors'], 'used': used, 'adv': runs}
        os.remove(p)
    js = ('// Generated by build/build_all.py: every sprite font\'s color layers (build/layerfont.py). Herdr on macOS draws\n'
          '// a font in one color, so a sprite is one text element per color layer, stacked. used: code point (hex) ->\n'
          '// bit mask (hex) of the layers that glyph draws.\n'
          f'export const LAYERS = {json.dumps(fams, separators=(",", ":"))};\n')
    for m in ('wq-party', 'wq-pane', 'wq-tabs'):
        with open(f'{ROOT}/mods/{m}/layers.js', 'w', encoding='utf-8', newline='\n') as fh:
            fh.write(js)
    print('layers.js:', len(fams), 'families')


def main():
    prev = sys.argv[sys.argv.index('--preview') + 1] if '--preview' in sys.argv else None
    party = f'{ROOT}/mods/wq-party'
    for d in ('fonts', 'faces', 'scenes', 'backdrops'):
        shutil.rmtree(f'{party}/{d}', ignore_errors=True)
        os.makedirs(f'{party}/{d}')
    if '--no-cut' not in sys.argv:
        run('cut_art.py', ROOT)
    run('anim.py', f'{HERE}/spr', f'{party}/fonts', f'{party}/faces', f'{HERE}/manifest.json',
        *([f'{prev}/atlas'] if prev else []))
    run('stage_art.py', ROOT, *([f'{prev}/atlas'] if prev else []))
    run('palettes.py', f'{ROOT}/mods/wq-chrome/scenes.js')
    run('backdrop.py', party)
    run('tiles.py', ROOT)
    layers_js()


if __name__ == '__main__':
    main()
